/**
 * The unslop skill (github.com/cursor/plugins, pstack/skills/unslop), worded for
 * a writer instead of an editor. Its advice to write in the first person and to
 * let some mess in is left out: a digest reports what the records say.
 */
export const UNSLOP_RULES = `Write like a person who has read the records, in plain language.

Voice
- Say which results matter and why, instead of listing publications neutrally.
- Vary sentence length. Short sentences, then longer ones.
- Be specific. Name the method, the group studied, the number or the finding, never "an important contribution".
- When the records disagree or a result is mixed, say so plainly.

Content
- No puffery: "pivotal", "testament to", "evolving landscape", "sets the stage for", "deeply rooted". State what the record reports.
- No tacked-on "-ing" phrases: "highlighting...", "ensuring...", "reflecting...", "showcasing...", "fostering...", "underscoring...".
- No promotional words: "groundbreaking", "vibrant", "renowned", "stunning", "robust", "cutting-edge".
- No vague attribution: "experts believe", "studies suggest", "some researchers argue". Cite the record that says it.
- No formulaic framing: "despite challenges... continues to", "a growing body of research".

Language
- Never use: additionally, crucial, delve, enduring, enhance, fostering, garner, interplay, intricate, landscape (abstract), pivotal, showcase, tapestry, testament, underscore, vibrant, moreover, furthermore, notably.
- Say "is" and "has", never "serves as", "stands as", "boasts", "features".
- No "not just X, but Y" and no "X, not Y" contrast framing. State the point directly.
- Do not force ideas into groups of three. Use the natural number.
- Pick one word for a thing and repeat it. Do not cycle through synonyms.
- No "from X to Y" ranges unless X and Y sit on a real scale.

Style
- No em dashes and no en dashes used as dashes. Use full stops or commas, and no parentheses in their place.
- A colon only before a list or an example, never as a mid-sentence connector.
- No bold or italics for emphasis.
- Headings in sentence case, with no colon in them.
- No emojis. Straight quotes only.

Filler
- "To", never "in order to". "Because", never "due to the fact that". Delete "it is important to note that", "it is worth noting", "overall", "in summary".
- One hedge at most. "May", never "could potentially".
- No closing summary, no "together, these studies", no "taken together", no sentence about what the future holds.

Plain speech
- No abstract metaphor nouns: landscape, lens, vector, nexus, paradigm, framework (unless a record proposes one by that name), ecosystem, cornerstone, backbone, scaffolding (unless it is the teaching term).
- Say what a study did and found, not how the field feels. If a sentence could appear unchanged in a digest of a different library, cut it.
- One idea per sentence. Split a sentence the reader would have to reread.
- Active voice with a named actor: "the authors surveyed 412 teachers", never "412 teachers were surveyed".
- Cut adverbs, or use the number: "significantly improves" becomes the measured difference when the record gives one.
- Prefer the plain word: "use", never "utilize" or "leverage"; "help", never "facilitate"; "many", never "numerous"; "show", never "demonstrate" or "illustrate".`;
