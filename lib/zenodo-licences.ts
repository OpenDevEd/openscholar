const IDS = new Set(ZENODO_LICENCES.map(([id]) => id));

/** Whether Zenodo takes this licence id. */
export const isZenodoLicence = (id: string) => IDS.has(id);

/** A licence's title by its id, or the id itself for one Zenodo doesn't have. */
